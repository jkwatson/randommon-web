/**
 * Resolve a leader/individual name (and, for witches, a coven name) for a
 * wilderness-encounter creature entry, following the source generator's
 * per-species naming rules.
 * @param {string} creatureName - raw table entry name, e.g. "BARROWBOGEY", "TREOWERE (CHAOTIC)"
 * @returns {{ name: string|null, covenName: string|null }}
 */
export function nameForCreature(creatureName) {
  const key = creatureName.replace(/\s*\([^)]*\)\s*$/, '').trim();
  const rule = CREATURE_NAME_RULES[key];
  if (!rule) return { name: null, covenName: null };

  switch (rule.kind) {
    case 'species':
      return { name: randomMonsterName(rule.key), covenName: null };
    case 'kindred':
      return { name: randomKindredName(rule.kindred, rule.gender), covenName: null };
    case 'firstOnly':
      return { name: randomKindredFirstName(rule.kindred), covenName: null };
    case 'elf':
      // Source rolls a 20% chance (1d10 > 8) of being a Frost Elf instead of a Wood Elf.
      return { name: randomKindredName(Math.random() < 0.2 ? 'FrostElf' : 'Elf'), covenName: null };
    case 'grimalkin':
      return { name: randomKindredName('Grimalkin'), covenName: null };
    case 'banshee':
      return { name: randomKindredFirstName('FrostElf'), covenName: null };
    case 'witch': {
      const w = randomWitchName();
      return { name: w.name, covenName: w.covenName };
    }
    default:
      return { name: null, covenName: null };
  }
}
