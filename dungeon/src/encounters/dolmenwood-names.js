// ── Helpers ─────────────────────────────────────────────────────────────

const pick = arr => arr[Math.floor(Math.random() * arr.length)];

// Resolves Perchance-style inline choices, e.g. "{Jack|Jill}" -> "Jack" or "Jill".
function resolveBraces(str) {
  return str.replace(/\{([^}]+)\}/g, (_, options) => pick(options.split('|')));
}

export function randomGender() {
  return Math.random() < 0.5 ? 'masculine' : 'feminine';
}

/**
 * Returns "First Surname" for a kindred with gendered names, or a flat single
 * name for kindreds with no surnames (Elf, Frost Elf).
 * @param {string} kindred - a key of KINDRED_NAMES
 * @param {'masculine'|'feminine'} [gender]
 */
export function randomKindredName(kindred, gender = randomGender()) {
  const pool = KINDRED_NAMES[kindred];
  if (!pool) return null;
  if (pool.flat) {
    const first = resolveBraces(pick(pool.flat));
    return pool.surnames ? `${first} ${resolveBraces(pick(pool.surnames))}` : first;
  }
  return `${resolveBraces(pick(pool[gender]))} ${resolveBraces(pick(pool.surnames))}`;
}

// First name only, no surname — a few creature types (kelpie, ogre) go by a single name.
export function randomKindredFirstName(kindred, gender = randomGender()) {
  const pool = KINDRED_NAMES[kindred];
  if (!pool) return null;
  return resolveBraces(pick(pool.flat ?? pool[gender]));
}

export function randomMonsterName(speciesKey) {
  const pool = MONSTER_NAMES[speciesKey];
  return pool ? pick(pool) : null;
}

export function randomWitchName() {
  const kindred = Math.random() < 1 / 6 ? 'Noble' : 'Human';
  return {
    name: randomKindredName(kindred, 'feminine'),
    covenName: `${pick(GROUP_NAMES.witchCovenFirst)} ${pick(GROUP_NAMES.witchCovenSecond)}`,
  };
}

export function randomAdventurePartyName() {
  return pick(GROUP_NAMES.adventureParty);
}

export function randomBanditCompanyName() {
  return pick(GROUP_NAMES.banditCompany);
}

export function randomLostShrine() {
  return pick(LOST_SHRINES);
}

