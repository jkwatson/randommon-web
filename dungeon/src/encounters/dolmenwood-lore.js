/**
 * Resolve an optional mount and/or entourage for the handful of species that have one.
 * @param {string} creatureName - raw table entry name
 * @param {boolean} hasLair - affects the size of some entourages (e.g. breggle-longhorn)
 * @returns {{ mount: string|null, entourage: string|null }}
 */
export function entourageForCreature(creatureName, hasLair) {
    const key = creatureName.replace(/\s*\([^)]*\)\s*$/, '').trim();
    const data = ENTOURAGE_DATA[key];
    if (!data) return {mount: null, entourage: null};

    return {
        mount: data.mount && Math.random() < data.mountChance ? data.mount() : null,
        entourage: data.entourage && Math.random() < data.entourageChance ? data.entourage(hasLair) : null,
    };
}

function tierForLevel(level) {
    const n = parseInt(level, 10) || 1;
    if (n <= 3) return 'Treasure03';
    if (n <= 7) return 'Treasure46';
    return 'Treasure79';
}

/**
 * Resolve lair/trait/hoard-tier/possession/vulnerability flavor for a wilderness-encounter
 * creature entry.
 * @param {string} creatureName - raw table entry name, e.g. "BARROWBOGEY", "TREOWERE (CHAOTIC)"
 * @param {string|number} [monsterLevel] - the creature's Shadowdark level, used to pick a treasure tier
 * @returns {{ trait: string|null, hasLair: boolean, hoardTier: string|null, possessionTier: string|null, vulnerability: string|null }}
 */
export function loreForCreature(creatureName, monsterLevel) {
    const key = creatureName.replace(/\s*\([^)]*\)\s*$/, '').trim();
    const lairInfo = LAIR_DATA[key];
    const traits = SPECIES_TRAITS[key];
    const hasLair = lairInfo ? Math.random() < lairInfo.lairChance : false;
    const extraConfig = SPECIES_EXTRAS[key];

    const lairs = SPECIES_LAIRS[key];

    return {
        trait: traits ? pick(traits) : null,
        hasLair,
        // A curated, species-specific lair description (from the Monster Book's own
        // LAIRS table) when one exists; species without curated coverage fall back
        // to the generic lairFeature/lairComplication tables in generator.js.
        lairDescription: hasLair && lairs ? pick(lairs) : null,
        hoardTier: hasLair && lairInfo?.hasHoard ? tierForLevel(monsterLevel) : null,
        // Possessions are what a creature carries day-to-day, so only relevant when
        // it's out and about, not when we're already describing its lair's hoard.
        possessionTier: !hasLair && lairInfo?.hasPoss ? tierForLevel(monsterLevel) : null,
        vulnerability: WYRM_SPECIES.has(key) ? pick(WYRM_VULNERABILITIES) : null,
        extra: extraConfig ? { label: extraConfig.label, text: extraConfig.generate ? extraConfig.generate() : pick(extraConfig.options) } : null,
    };
}
